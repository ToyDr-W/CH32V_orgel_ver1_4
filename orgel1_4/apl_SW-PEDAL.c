//ｱﾝﾊﾟﾝﾏﾝﾄﾞﾗｲﾌのﾍﾟﾀﾞﾙ部をﾏｲｺﾝ換装するためのｱﾌﾟﾘｹｰｼｮﾝ例


//==============================================
//構成情報(個別ｱﾌﾟﾘｹｰｼｮﾝだけで使うもの)
//==============================================
#define	SLEEP_TMR	1000		//Sleepに入る前の時限[ms]
					//　操作の評価時間よりも長くすること


//==============================================
//固有の作業域
//==============================================
static unsigned short smp=4000;			//ｴﾝｼﾞﾝ音のｻﾝﾌﾟﾙﾚｰﾄ[sps]


//==============================================
//ｱﾌﾟﾘの初期設定
//==============================================
static void apl_init(void)
{

DBG_C('\n');
DBG_C('$');

DBG_C('p');
	GPIO_INPU(SW0_GPIO,SW0_BIT);		//入力ﾓｰﾄﾞﾌﾟﾙｱｯﾌﾟする

	VOICEN_SEL(0,1);
	VOICEN_SMP(0,smp);


DBG_C('>');
}



//==============================================
//固有の処理(ｺｰﾙﾊﾞｯｸ関数)
//
//動作仕様
//・ｴﾝｼﾞﾝ音は音声N0
//
//音声
//1.ｱｲﾄﾞﾘﾝｸﾞ
//==============================================
static void CB_KOYUU(void)
{


	if(GPIO_R(SW0_GPIO,SW0_BIT))
	{
		if(smp>4000) smp-=200;
	}
	else
	{
		if(smp<15000) smp+=500;
	}
	VOICEN_SMP(0,smp);		//ｻﾝﾌﾟﾙﾚｰﾄを設定する

DBG_C('>');
}


//==============================================
//演奏終了時の処理(ｺｰﾙﾊﾞｯｸ関数)
//==============================================
static void CB_SONG_END(void)
{
}


//==============================================
//音声N再生終了時の処理(ｺｰﾙﾊﾞｯｸ関数)
//==============================================
static void CB_VOICEN_END(
	unsigned char ch)			//音声Nのch番号
{

	//ｴﾝｼﾞﾝの制御
	if(ch==0)
	{
		VOICEN_SEL(0,1);		//定常音を連続再生する
		VOICEN_SMP(0,smp);		//ｻﾝﾌﾟﾙﾚｰﾄを設定する
	}
}
